#!/usr/bin/env python3
"""Benchmark harness: measures wall time, peak RSS and recovery stats.

Usage:
    python scripts/bench.py [binary ...]

With no arguments, benchmarks the compiled test fixtures plus a few
system binaries when present. Results are printed as a table and written
to ``docs/benchmarks.md``.
"""

from __future__ import annotations

import json
import os
import platform
import resource
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))


def _peak_rss_mb() -> float:
    usage = resource.getrusage(resource.RUSAGE_SELF)
    # Linux reports KiB, macOS reports bytes
    divisor = 1024 if platform.system() != "Darwin" else 1024 * 1024
    return usage.ru_maxrss / divisor


def bench_one(path: str, runs: int = 3) -> dict:
    """Benchmark the full analysis pipeline on *path* (in-process)."""
    from native_re_toolkit import open_binary
    from native_re_toolkit.analysis.strings import extract_strings
    from native_re_toolkit.analysis.xrefs import build_xrefs
    from native_re_toolkit.disasm.discovery import discover_functions

    times = []
    rss = []
    stats = {}
    for _ in range(runs):
        t0 = time.perf_counter()
        b = open_binary(path)
        res = discover_functions(b)
        strings = extract_strings(b)
        db = build_xrefs(b, res.functions, strings)
        t1 = time.perf_counter()
        times.append(t1 - t0)
        rss.append(_peak_rss_mb())
        stats = {
            "format": b.format,
            "arch": b.arch,
            "size_bytes": b.file_size,
            "functions": res.total,
            "heuristic_functions": res.from_heuristics,
            "strings": len(strings),
            "xrefs": len(db.xrefs),
            "instructions": sum(f.num_insns for f in res.functions.values()),
        }
    return {
        "path": path,
        "time_s_best": min(times),
        "time_s_median": statistics.median(times),
        "peak_rss_mb": max(rss),
        **stats,
    }


def main(argv: list[str]) -> int:
    paths = argv[1:]
    if not paths:
        build = ROOT / "tests" / "fixtures" / "build"
        if not build.exists():
            subprocess.run(
                [sys.executable, "-m", "pytest", "--collect-only", "-q"],
                cwd=ROOT, check=False,
            )
        candidates = [
            build / "hello",
            build / "branchy_o2",
            "/usr/bin/gcc-12",
            "/usr/bin/python3.11",
            "/usr/bin/perl",
        ]
        paths = [str(p) for p in candidates if Path(p).exists()]

    if not paths:
        print("no benchmark targets found", file=sys.stderr)
        return 1

    print(f"benchmarking {len(paths)} binaries (3 runs each)...")
    results = []
    for p in paths:
        try:
            r = bench_one(p)
        except Exception as exc:
            print(f"  {p}: FAILED ({exc})")
            continue
        results.append(r)
        print(
            f"  {Path(p).name:<20} {r['size_bytes']/1024:>9.1f} KiB  "
            f"{r['time_s_median']:>7.3f} s  {r['peak_rss_mb']:>7.1f} MB  "
            f"{r['functions']:>6} funcs  {r['instructions']:>8} insns"
        )

    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    out = docs / "benchmarks.md"
    lines = [
        "# Benchmarks",
        "",
        f"Machine: {platform.system()} {platform.machine()}, "
        f"{os.cpu_count()} CPUs, Python {platform.python_version()}",
        "",
        "Full pipeline: load -> function discovery (incl. CFG) -> strings -> xrefs.",
        "",
        "| Binary | Size | Time (median) | Peak RSS | Functions | Instructions | Xrefs |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {Path(r['path']).name} | {r['size_bytes']/1024:.1f} KiB | "
            f"{r['time_s_median']:.3f} s | {r['peak_rss_mb']:.1f} MB | "
            f"{r['functions']} | {r['instructions']} | {r['xrefs']} |"
        )
    lines += [
        "",
        "<!-- auto-generated by scripts/bench.py; numbers are indicative -->",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"\nwrote {out}")
    (docs / "benchmarks.json").write_text(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
